const DAY_MS = 86_400_000;
const HOUR_MS = 3_600_000;

/** Days, hours and minutes of a span, magnitude only — the sentence says "left" or "ago". */
function parts(ms: number): { d: number; h: number; m: number } {
  const abs = Math.abs(ms);
  return { d: Math.floor(abs / DAY_MS), h: Math.floor((abs % DAY_MS) / HOUR_MS), m: Math.floor((abs % HOUR_MS) / 60_000) };
}

function ordinal(n: number): string {
  const tens = n % 100;
  if (tens >= 11 && tens <= 13) return `${n}th`;
  return `${n}${n % 10 === 1 ? 'st' : n % 10 === 2 ? 'nd' : n % 10 === 3 ? 'rd' : 'th'}`;
}

